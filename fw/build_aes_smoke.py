"""Emit a small, auditable RV32I assembly program and its ready-to-use 4 KB ROM.

No assembler is needed for lab simulation. Each emitted instruction has a
literal encoding and readable assembly; assertions check ranges and ROM fit.
This helper does not implement AES or calculate the expected ciphertexts.
"""
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parent
CASES=[
    ("demo", "000102030405060708090a0b0c0d0e0f", "00112233445566778899aabbccddeeff", "69c4e0d86a7b0430d8cdb78070b4c55a"),
    ("repeat_demo_key", "000102030405060708090a0b0c0d0e0f", "00112233445566778899aabbccddeeff", "69c4e0d86a7b0430d8cdb78070b4c55a"),
    ("zero", "00000000000000000000000000000000", "00000000000000000000000000000000", "66e94bd4ef8a2c3b884cfa59ca342b2e"),
    ("fips_example", "2b7e151628aed2a6abf7158809cf4f3c", "3243f6a8885a308d313198a2e0370734", "3925841d02dc09fbdc118597196a0b32"),
]
words=[];lines=["# Generated by fw/build_aes_smoke.py; see docs/aes_mmio.md.",
    "# Constants are encoded in instructions: data loads cannot read Harvard ROM.",
    ".section .text", ".globl _start"]
labels={};fixups=[];listing=[]
def emit(word,text):
    assert 0<=word<=0xffffffff
    listing.append((len(words)*4,text));words.append(word);lines.append("    "+text)
def label(name):
    assert name not in labels
    labels[name]=len(words)*4;lines.append(name+":")
def addi(rd,rs,imm):
    assert -2048<=imm<=2047
    emit(((imm&4095)<<20)|(rs<<15)|(rd<<7)|0x13,f"addi x{rd}, x{rs}, {imm}")
def constant(rd,value):
    value&=0xffffffff
    lo=((value&4095)^2048)-2048;hi=((value+0x800)>>12)&0xfffff
    emit((hi<<12)|(rd<<7)|0x37,f"lui x{rd}, 0x{hi:05x}");addi(rd,rd,lo)
def lw(rd,rs,off):
    assert -2048<=off<=2047 and off%4==0
    emit(((off&4095)<<20)|(rs<<15)|(2<<12)|(rd<<7)|3,f"lw x{rd}, {off}(x{rs})")
def sw(rs,base,off):
    assert -2048<=off<=2047 and off%4==0
    emit(((off&0xfe0)<<20)|(rs<<20)|(base<<15)|(2<<12)|((off&31)<<7)|0x23,f"sw x{rs}, {off}(x{base})")
def branch(f3,a,b,dest):
    fixups.append((len(words),"b",f3,a,b,dest));emit(0,f"{'beq' if f3==0 else 'bne'} x{a}, x{b}, {dest}")
def jump(dest):
    fixups.append((len(words),"j",0,0,0,dest));emit(0,f"jal x0, {dest}")
def le_words(hex_value):
    data=bytes.fromhex(hex_value)
    return [int.from_bytes(data[i:i+4],"little") for i in range(0,16,4)]

label("_start")
constant(2,0x2000)  # aligned stack top; this leaf program never pushes
constant(1,0x1000);constant(3,0x40000000)
addi(31,0,0);sw(31,1,64)
for idx,(name,key,plain,cipher) in enumerate(CASES):
    lines.append(f"# Block {idx}: {name}. Result at RAM 0x{0x1000+16*idx:04x}.")
    if idx!=1:
        for w,value in enumerate(le_words(key)):
            constant(4,value);sw(4,3,16+4*w)
    for w,value in enumerate(le_words(plain)):
        constant(4,value);sw(4,3,32+4*w)
    addi(4,0,1);sw(4,3,0);addi(5,0,100)
    label(f"poll_{idx}");lw(6,3,4)
    emit((2<<20)|(6<<15)|(7<<12)|(6<<7)|0x13,"andi x6, x6, 2")
    branch(1,6,0,f"read_{idx}");addi(5,5,-1);branch(1,5,0,f"poll_{idx}");jump("timeout")
    label(f"read_{idx}")
    for w,value in enumerate(le_words(cipher)):
        lw(8,3,48+4*w);sw(8,1,16*idx+4*w)
        constant(7,value);branch(1,8,7,"mismatch")
addi(4,0,1);sw(4,1,64);addi(31,0,1);label("pass_loop");jump("pass_loop")
label("mismatch");addi(4,0,2);sw(4,1,64);addi(31,0,2);jump("fail_loop")
label("timeout");addi(4,0,3);sw(4,1,64);addi(31,0,3)
label("fail_loop");jump("fail_loop")
for n,kind,f3,a,b,dest in fixups:
    off=labels[dest]-4*n
    assert off%4==0
    if kind=="b":
        assert -4096<=off<=4094
        words[n]=((off&0x1000)<<19)|((off&0x7e0)<<20)|(b<<20)|(a<<15)|(f3<<12)|((off&30)<<7)|((off&0x800)>>4)|0x63
    else:
        assert -(1<<20)<=off<(1<<20)
        words[n]=((off&0x100000)<<11)|((off&0x7fe)<<20)|((off&0x800)<<9)|(off&0xff000)|0x6f
assert len(words)<=1024
allowed={0x37,0x13,3,0x23,0x63,0x6f}
assert all((w&127) in allowed for w in words)
(ROOT/'src/aes_smoke.S').write_text('\n'.join(lines)+'\n',encoding='ascii')
(ROOT/'aes_smoke.hex').write_text(''.join(f'{w:08x}\n' for w in words+[0]*(1024-len(words))),encoding='ascii')
(ROOT/'aes_smoke.lst').write_text(''.join(f'{pc:04x}  {words[pc//4]:08x}  {asm}\n' for pc,asm in listing),encoding='ascii')
manifest={'code_bytes':4*len(words),'rom_capacity_bytes':4096,'result_ram_bytes':68,'stack_top':'0x2000',
    'stack_bytes_used':0,'status_register':'x31: 0=running, 1=pass, 2=mismatch, 3=poll timeout',
    'status_ram_address':'0x1040','labels':labels,'cases':[dict(zip(('name','key','plaintext','ciphertext'),c)) for c in CASES]}
(ROOT/'aes_smoke_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='ascii')
print(f'AES ROM: {len(words)} instructions / {len(words)*4} bytes; RAM results 68 bytes; four checked blocks.')
