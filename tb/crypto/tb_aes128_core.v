`timescale 1ns / 1ps

module tb_aes128_core;
    reg clk = 0;
    always #5 clk = ~clk;
    reg rst = 1, start = 0;
    reg [127:0] key = 0, plaintext = 0;
    wire busy, done;
    wire [127:0] ciphertext;
    aes128_core dut (.clk(clk), .rst(rst), .start(start), .key(key),
        .plaintext(plaintext), .busy(busy), .done(done), .ciphertext(ciphertext));

    `include "aes_reference.vh"
    `include "aes128_vector_count.vh"
    reg [383:0] vectors [0:NIST_CASES-1];
    localparam [127:0] DEMO_KEY = 128'h000102030405060708090a0b0c0d0e0f;
    localparam [127:0] DEMO_PT = 128'h00112233445566778899aabbccddeeff;
    localparam [127:0] DEMO_CT = 128'h69c4e0d86a7b0430d8cdb78070b4c55a;
    localparam [127:0] ZERO_CT = 128'h66e94bd4ef8a2c3b884cfa59ca342b2e;
    integer checks = 0, blocks = 0;
    integer i, j, offset;
    reg [127:0] random_key, random_pt, expected;
    reg [31:0] random_state = 32'hae512810;

    task tick;
        begin @(posedge clk); #1; end
    endtask

    task check_value;
        input [127:0] actual, wanted;
        input [255:0] label_text;
        begin
            checks = checks + 1;
            if (actual !== wanted) begin
                $display("FAIL %0s block=%0d time=%0t actual=%032h expected=%032h",
                    label_text, blocks, $time, actual, wanted);
                $fatal(1, "AES core mismatch");
            end
        end
    endtask

    task check_status;
        input wanted_busy, wanted_done;
        input [127:0] wanted_ct;
        begin
            check_value({busy,done}, {wanted_busy,wanted_done}, "BUSY/DONE cycle contract");
            check_value(ciphertext, wanted_ct, "Ciphertext publication/retention");
        end
    endtask

    task accept_block;
        input [127:0] new_key, new_pt;
        begin
            @(negedge clk);
            key = new_key; plaintext = new_pt; start = 1;
            tick;
            check_status(1,0,128'b0);
        end
    endtask

    task finish_block;
        input [127:0] wanted_ct;
        input perturb_inputs, hold_start;
        integer cycle;
        begin
            for (cycle = 1; cycle <= 11; cycle = cycle + 1) begin
                @(negedge clk);
                // Includes a START on the completion edge. It must not queue.
                start = hold_start || (perturb_inputs && ((cycle%3 == 0) || cycle == 11));
                if (perturb_inputs) begin
                    key = ~key;
                    plaintext = {plaintext[119:0],plaintext[127:120]} ^ 128'h1;
                end
                tick;
                if (cycle < 11) check_status(1,0,128'b0);
                else check_status(0,1,wanted_ct);
            end
            blocks = blocks + 1;
        end
    endtask

    task run_block;
        input [127:0] new_key, new_pt, wanted_ct;
        integer idle_cycle;
        begin
            accept_block(new_key,new_pt);
            finish_block(wanted_ct,1,0);
            for (idle_cycle = 0; idle_cycle < 3; idle_cycle = idle_cycle + 1) begin
                @(negedge clk); start = 0;
                tick; check_status(0,1,wanted_ct);
            end
        end
    endtask

    initial begin
        #500000;
        $fatal(1,"FAIL AES core watchdog: simulation did not finish");
    end

    initial begin
`ifdef VIVADO_GUI
        $readmemh("aes128_kat.mem",vectors);
`else
        $readmemh("tb/crypto/vectors/aes128_kat.mem",vectors);
`endif
        // Reset beats START, including at power-up.
        start = 1; tick; check_status(0,0,128'b0);
        @(negedge clk); start = 0; rst = 0;
        tick; check_status(0,0,128'b0);

        // A familiar first block makes the GUI waveform easy to inspect.
        run_block(DEMO_KEY,DEMO_PT,DEMO_CT);
        run_block(128'b0,128'b0,ZERO_CT);
        run_block(128'h2b7e151628aed2a6abf7158809cf4f3c,
                  128'h3243f6a8885a308d313198a2e0370734,
                  128'h3925841d02dc09fbdc118597196a0b32);

        // Expected values are published NIST answers, never generated by RTL.
        // Validate our separate mathematical model against these answers too.
        for (i = 0; i < NIST_CASES; i = i + 1) begin
            if ((^vectors[i]) === 1'bx) $fatal(1,"FAIL missing NIST vector %0d",i);
            check_value(ref_encrypt(vectors[i][383:256],vectors[i][255:128]),
                        vectors[i][127:0],"Reference vs published NIST");
            run_block(vectors[i][383:256],vectors[i][255:128],vectors[i][127:0]);
        end
        for (i = 0; i < 256; i = i + 1) begin
            for (j = 0; j < 4; j = j + 1) begin
                random_state = next_random(random_state);
                random_key[j*32 +: 32] = random_state;
                random_state = next_random(random_state);
                random_pt[j*32 +: 32] = random_state;
            end
            expected = ref_encrypt(random_key,random_pt);
            run_block(random_key,random_pt,expected);
        end

        // Reset each stage: next edge after capture through completion edge.
        for (offset = 0; offset <= 10; offset = offset + 1) begin
            accept_block(DEMO_KEY,DEMO_PT);
            for (j = 0; j < offset; j = j + 1) begin
                @(negedge clk); start = 0;
                tick; check_status(1,0,128'b0);
            end
            @(negedge clk); rst = 1; start = 1;
            tick; check_status(0,0,128'b0);
            check_value(dut.state,128'b0,"Reset clears state");
            check_value(dut.round_key,128'b0,"Reset clears key");
            check_value(dut.round_index,128'b0,"Reset clears round counter");
            @(negedge clk); rst = 0; start = 0;
            repeat (13) begin tick; check_status(0,0,128'b0); end
            run_block(DEMO_KEY,DEMO_PT,DEMO_CT);
        end

        // Level START: ignored until completion, accepted at earliest E12.
        accept_block(DEMO_KEY,DEMO_PT);
        finish_block(DEMO_CT,0,1);
        accept_block(128'b0,128'b0);
        finish_block(ZERO_CT,0,0);
        @(negedge clk); start = 0;
        tick; check_status(0,1,ZERO_CT);
        // Also clear a completed result with reset.
        @(negedge clk); rst = 1;
        tick; check_status(0,0,128'b0);

        $display("PASS tb_aes128_core: %0d checks, %0d completed blocks; %0d NIST, 256 random, 11 reset-abort points; latency=11 clocks, earliest restart=12 clocks",checks,blocks,NIST_CASES);
        $finish;
    end
endmodule
