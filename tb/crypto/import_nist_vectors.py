"""Offline import of AES-128 encrypt KATs. No expected ciphertext is computed.

Run only to regenerate the checked-in fixtures after inspecting their source.
The original public NIST archive is retained under docs/references/aes/.
"""
from pathlib import Path
import hashlib
import json
import re
import zipfile

ROOT = Path(__file__).resolve().parents[2]
ARCHIVE = ROOT / 'docs/references/aes/KAT_AES.zip'
EXPECTED_SHA256 = 'a203b16c9246b2ebae31dee5de21a606be80cf78ceabaca37150236fa098eb60'
assert hashlib.sha256(ARCHIVE.read_bytes()).hexdigest() == EXPECTED_SHA256
sources = ['ECBGFSbox128.rsp', 'ECBKeySbox128.rsp', 'ECBVarKey128.rsp', 'ECBVarTxt128.rsp']
rows, manifest = [], []
with zipfile.ZipFile(ARCHIVE) as archive:
    for name in sources:
        data = archive.read(name)
        (ARCHIVE.parent / name).write_bytes(data)
        encryption = data.decode('ascii').split('[ENCRYPT]')[1].split('[DECRYPT]')[0]
        found = re.findall(r'COUNT\s*=\s*(\d+)\s+KEY\s*=\s*([0-9a-fA-F]{32})\s+'
                           r'PLAINTEXT\s*=\s*([0-9a-fA-F]{32})\s+'
                           r'CIPHERTEXT\s*=\s*([0-9a-fA-F]{32})', encryption)
        assert found, name
        first = len(rows)
        for count, key, plaintext, ciphertext in found:
            assert int(count) == len(rows) - first, (name, count)
            rows.append((key + plaintext + ciphertext).lower())
        manifest.append(dict(file=name, first_index=first, cases=len(found),
                             sha256=hashlib.sha256(data).hexdigest()))
assert len(rows) == 284
out = ROOT / 'tb/crypto/vectors'
out.mkdir(parents=True, exist_ok=True)
(out / 'aes128_kat.mem').write_text('\n'.join(rows) + '\n', encoding='ascii')
(out / 'aes128_vector_count.vh').write_text(
    '// Generated by tb/crypto/import_nist_vectors.py\n'
    f'localparam integer NIST_CASES = {len(rows)};\n', encoding='ascii')
(ARCHIVE.parent / 'manifest.json').write_text(json.dumps(dict(
    retrieved='2026-10-24',
    source='https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/aes/KAT_AES.zip',
    archive_sha256=EXPECTED_SHA256,
    format='aes128_kat.mem: 384-bit rows, key[383:256], plaintext[255:128], ciphertext[127:0]',
    selection='AES-128 ECB encryption KAT sections only; ECB used to test a single raw block',
    files=manifest), indent=2) + '\n', encoding='utf-8')
print(f'Imported {len(rows)} published encryption cases from {len(sources)} NIST files.')
